package it.termox.arvolo

import android.content.Context
import android.content.Intent
import android.net.Uri
import android.provider.OpenableColumns
import org.json.JSONArray
import java.io.File
import java.util.UUID

/**
 * What another app handed over through the system share sheet.
 *
 * The shell declares `ACTION_SEND` / `ACTION_SEND_MULTIPLE` for any type, so
 * Arvolo is in the list when somebody taps Condividi in Foto, Files, a browser
 * or a chat. What arrives is `content://` URIs with a grant that lasts as long
 * as this activity does, and text, which is not a file at all. Both are copied
 * into the app's own storage here — while the grant is live — and the paths
 * handed to Rust, which registers them like a pick and tells the screen. The
 * screen then opens Scambia with the files already in hand (the design's 11e).
 *
 * Kept out of the generated `MainActivity` as far as possible: `gen/android`
 * is regenerated by `tauri android init`, and `npm run mobile:patch` puts this
 * file and the manifest's intent filter back.
 */
object Shared {
    /** Rust's door — `Java_it_termox_arvolo_Shared_onShared` in `share_inbox.rs`. */
    @JvmStatic external fun onShared(json: String)

    /** L'altra porta: il contenuto di un `.arvolo` aperto con noi. */
    @JvmStatic external fun onTicket(text: String)

    /** Un biglietto non è un file da mandare: è un file da *leggere*, e quello
     *  che conta è la riga che c'è dentro. Arriva come `ACTION_VIEW` da File,
     *  dalla posta, da una chat — ovunque qualcuno tocchi un `.arvolo` — e da
     *  qui va dritto in Rust, che lo tiene finché la schermata non lo chiede.
     *
     *  Il tetto sulla dimensione non è prudenza generica: un biglietto è una
     *  riga, e qualunque cosa più grande non è un biglietto, quindi leggerla
     *  per intero sarebbe solo un modo di farsi passare un file arbitrario per
     *  la testa. */
    private const val TICKET_CAP = 64 * 1024

    @JvmStatic
    fun take(ctx: Context, intent: Intent?) {
        val action = intent?.action ?: return
        if (action == Intent.ACTION_VIEW) {
            val uri = intent.data
            if (uri != null) {
                try {
                    val text = ctx.contentResolver.openInputStream(uri)?.use { input ->
                        String(input.readNBytes(TICKET_CAP), Charsets.UTF_8)
                    }
                    if (!text.isNullOrBlank()) onTicket(text)
                } catch (e: Exception) {
                    android.util.Log.w("arvolo", "ticket not read: $e")
                }
            }
            // Consumato, come una condivisione: una rotazione non deve aprirlo
            // una seconda volta.
            intent.action = Intent.ACTION_MAIN
            intent.data = null
            return
        }
        if (action != Intent.ACTION_SEND && action != Intent.ACTION_SEND_MULTIPLE) return
        val dir = File(ctx.filesDir, "shared/" + UUID.randomUUID().toString())
        dir.mkdirs()
        val paths = ArrayList<String>()

        val uris = ArrayList<Uri>()
        if (action == Intent.ACTION_SEND) {
            @Suppress("DEPRECATION")
            (intent.getParcelableExtra<Uri>(Intent.EXTRA_STREAM))?.let { uris.add(it) }
        } else {
            @Suppress("DEPRECATION")
            intent.getParcelableArrayListExtra<Uri>(Intent.EXTRA_STREAM)?.let { uris.addAll(it) }
        }
        for (uri in uris) {
            try {
                val name = displayName(ctx, uri)
                val out = unclaimed(dir, name)
                ctx.contentResolver.openInputStream(uri)?.use { input ->
                    out.outputStream().use { input.copyTo(it) }
                }
                if (out.exists()) paths.add(out.absolutePath)
            } catch (e: Exception) {
                android.util.Log.w("arvolo", "shared item skipped: $e")
            }
        }
        // Text shared on its own — a link, a sentence — travels as a file,
        // because files are what the engine sends.
        if (uris.isEmpty()) {
            val text = intent.getCharSequenceExtra(Intent.EXTRA_TEXT)?.toString()
            if (!text.isNullOrBlank()) {
                val subject = intent.getStringExtra(Intent.EXTRA_SUBJECT)
                val base = (subject?.takeIf { it.isNotBlank() } ?: "testo")
                    .replace(Regex("[^A-Za-z0-9._ -]"), "_").take(60)
                val out = unclaimed(dir, "$base.txt")
                out.writeText(text)
                paths.add(out.absolutePath)
            }
        }
        // Consumed: a rotation or a relaunch must not hand the same share over
        // a second time.
        intent.action = Intent.ACTION_MAIN
        intent.removeExtra(Intent.EXTRA_STREAM)
        intent.removeExtra(Intent.EXTRA_TEXT)
        if (paths.isEmpty()) {
            dir.delete()
            return
        }
        onShared(JSONArray(paths).toString())
    }

    private fun displayName(ctx: Context, uri: Uri): String {
        try {
            ctx.contentResolver.query(uri, arrayOf(OpenableColumns.DISPLAY_NAME), null, null, null)?.use { c ->
                if (c.moveToFirst()) {
                    val i = c.getColumnIndex(OpenableColumns.DISPLAY_NAME)
                    if (i >= 0) c.getString(i)?.takeIf { it.isNotBlank() }?.let { return safe(it) }
                }
            }
        } catch (_: Exception) {}
        return safe(uri.lastPathSegment ?: "file")
    }

    /** One path component, never a traversal. */
    private fun safe(name: String): String =
        name.substringAfterLast('/').substringAfterLast(':').ifBlank { "file" }

    private fun unclaimed(dir: File, name: String): File {
        var f = File(dir, name)
        var n = 2
        val stem = name.substringBeforeLast('.', name)
        val ext = if (name.contains('.')) "." + name.substringAfterLast('.') else ""
        while (f.exists()) { f = File(dir, "$stem-$n$ext"); n++ }
        return f
    }
}
